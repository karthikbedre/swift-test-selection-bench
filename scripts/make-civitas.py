ENV = {
    "GIT_AUTHOR_NAME": "Civitas benchmark", "GIT_AUTHOR_EMAIL": "civitas@example.invalid",
    "GIT_COMMITTER_NAME": "Civitas benchmark", "GIT_COMMITTER_EMAIL": "civitas@example.invalid",
}


def git(repo: Path, *args: str, date: str | None = None) -> str:
    env = {**os.environ, **ENV}
    if date:
        env["GIT_AUTHOR_DATE"] = env["GIT_COMMITTER_DATE"] = date
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True,
                          env=env).stdout.strip()


def build(repo: Path) -> dict[str, str]:
    if repo.exists():
        shutil.rmtree(repo)
    shutil.copytree(PACKAGE, repo)
    (repo / "README.md").write_text(README)
    (repo / ".github" / "workflows").mkdir(parents=True)
    (repo / ".github" / "workflows" / "ci.yml").write_text(CI)
    (repo / "scripts").mkdir()
    (repo / "scripts" / "check.sh").write_text(CHECK)
    (repo / ".gitignore").write_text(".build/\n.swiftpm/\n")
    git(repo, "init", "-q", "-b", "main")
    git(repo, "config", "core.fileMode", "false")
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", "Civitas base", date="2026-11-01T00:00:00Z")
    commits = {}
    for n, (eid, kind, module, depth, path, old, new) in enumerate(EDITS, start=1):
        f = repo / path
        text = f.read_text()
        if text.count(old) != 1:
            sys.exit(f"edit {eid}: expected exactly one match in {path}, found {text.count(old)}")
        f.write_text(text.replace(old, new))
        git(repo, "add", "-A")
        git(repo, "commit", "-q", "-m", f"edit {eid}: {kind} in {module}",
            date=f"2026-11-01T{n // 60:02d}:{n % 60:02d}:00Z")
        commits[git(repo, "rev-parse", "HEAD")] = eid
    return commits


def catalogue() -> list[dict]:
    return [{"id": e[0], "kind": e[1], "module": e[2], "depth": e[3], "path": e[4]} for e in EDITS]


if __name__ == "__main__":
    repo = Path(sys.argv[1]).resolve()
    commits = build(repo)
    (repo.parent / "civitas-edits.json").write_text(json.dumps(
        {"head": git(repo, "rev-parse", "HEAD"), "commits": commits, "edits": catalogue()}, indent=1))
    print(f"{len(commits)} edits, head {git(repo, 'rev-parse', 'HEAD')}")
